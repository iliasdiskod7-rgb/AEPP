PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS Users (
 Id TEXT PRIMARY KEY, Email TEXT NOT NULL, NormalizedEmail TEXT NOT NULL UNIQUE,
 PasswordHash TEXT NOT NULL, FullName TEXT NOT NULL, Role TEXT NOT NULL CHECK(Role IN ('STUDENT','TEACHER')), CreatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS DailyChallengeCompletions (
 Id TEXT PRIMARY KEY, UserId TEXT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 ChallengeDate TEXT NOT NULL, Score INTEGER NOT NULL CHECK(Score BETWEEN 0 AND 3), XPEarned INTEGER NOT NULL CHECK(XPEarned>=0),
 CompletedAt TEXT NOT NULL, ResultJson TEXT NOT NULL, UNIQUE(UserId,ChallengeDate)
);
CREATE TABLE IF NOT EXISTS SavedExams (
 Id TEXT PRIMARY KEY, UserId TEXT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 Title TEXT NOT NULL, Format TEXT NOT NULL CHECK(Format IN ('examDto','examJson')), ContentJson TEXT NOT NULL, CreatedAt TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_SavedExams_User ON SavedExams(UserId,CreatedAt);
CREATE TABLE IF NOT EXISTS AuthSessions (
 Id TEXT PRIMARY KEY, UserId TEXT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 ExpiresAt INTEGER NOT NULL, Revoked INTEGER NOT NULL DEFAULT 0 CHECK(Revoked IN (0,1))
);
