export function fullProgram(pattern: AlgorithmPattern): string {
  return ['ΠΡΟΓΡΑΜΜΑ Παράδειγμα', 'ΜΕΤΑΒΛΗΤΕΣ', pattern.declarations, 'ΑΡΧΗ', pattern.setup, pattern.code, 'ΤΕΛΟΣ_ΠΡΟΓΡΑΜΜΑΤΟΣ'].filter(Boolean).join('\n')
}
export function matchesPattern(pattern: AlgorithmPattern, query: string): boolean {
  const normalize = (text: string) => text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('el-GR').trim()
  return normalize([pattern.title, pattern.summary, pattern.category, ...pattern.steps].join(' ')).includes(normalize(query))
}
